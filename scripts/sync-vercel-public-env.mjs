#!/usr/bin/env node
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const PROD_API_TARGET = 'https://cgraph-backend-prod-v3.fly.dev';
const PROD_WS_TARGET = 'wss://cgraph-backend-prod-v3.fly.dev';

const rootDir = process.cwd();
const sourcePath = path.join(rootDir, '.vercel', '.env.production.local');
const examplePath = path.join(rootDir, 'apps', 'web', '.env.example');
const targetPath = path.join(rootDir, 'apps', 'web', '.env.local');
const DEV_TURNSTILE_BYPASS_TOKEN = 'CGRAPH_DEV_TURNSTILE_BYPASS_TOKEN';

function parseEnv(contents) {
  const entries = new Map();

  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const separatorIndex = line.indexOf('=');
    if (separatorIndex < 0) continue;

    const key = line.slice(0, separatorIndex).trim();
    let value = line.slice(separatorIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    entries.set(key, sanitizeEnvValue(value));
  }

  return entries;
}

function sanitizeEnvValue(value) {
  return value.replace(/(?:\\r|\\n|[\r\n])+$/g, '').trim();
}

function formatEnvValue(value) {
  if (/^[A-Za-z0-9_./:@?&=,+-]*$/.test(value)) {
    return value;
  }

  return JSON.stringify(value);
}

if (!existsSync(sourcePath)) {
  console.error(
    [
      'Missing .vercel/.env.production.local.',
      'Run `vercel env pull .vercel/.env.production.local --environment=production` first.',
    ].join('\n')
  );
  process.exit(1);
}

const source = parseEnv(readFileSync(sourcePath, 'utf8'));
const existingTarget = existsSync(targetPath) ? parseEnv(readFileSync(targetPath, 'utf8')) : new Map();
const example = existsSync(examplePath)
  ? parseEnv(readFileSync(examplePath, 'utf8'))
  : new Map();
const publicViteEntries = new Map(
  [...source.entries()].filter(([key]) => key.startsWith('VITE_'))
);

for (const [key, value] of example.entries()) {
  if (!key.startsWith('VITE_')) continue;
  if (publicViteEntries.get(key)) continue;
  if (!value) continue;
  publicViteEntries.set(key, value);
}

if (!publicViteEntries.get('VITE_TURNSTILE_SITE_KEY')) {
  console.error('VITE_TURNSTILE_SITE_KEY is missing from the pulled Vercel env.');
  process.exit(1);
}

// In local development, keep browser requests same-origin so cookies and CORS
// behave like Vercel rewrites. Vite proxies these paths to Fly production.
publicViteEntries.set('VITE_API_URL', '');
publicViteEntries.set('VITE_WS_URL', '');
publicViteEntries.set('VITE_SOCKET_URL', '');
publicViteEntries.set('VITE_DEV_API_TARGET', PROD_API_TARGET);
publicViteEntries.set('VITE_DEV_WS_TARGET', PROD_WS_TARGET);
// Local dev uses Vite's same-origin proxy plus a server-side bypass header.
// Production still enforces real Turnstile from Vercel/Fly configuration.
publicViteEntries.set('VITE_DEV_DISABLE_TURNSTILE', 'true');

const devTurnstileBypassToken =
  existingTarget.get(DEV_TURNSTILE_BYPASS_TOKEN) || randomBytes(32).toString('base64url');

const preferredOrder = [
  'VITE_APP_NAME',
  'VITE_APP_VERSION',
  'VITE_TURNSTILE_SITE_KEY',
  'VITE_VAPID_PUBLIC_KEY',
  'VITE_SENTRY_DSN',
  'VITE_ENABLE_SENTRY',
  'VITE_ENABLE_ANALYTICS',
  'VITE_ENABLE_LOGGING',
  'VITE_ENABLE_QUERY_CACHE_PERSISTANCE',
  'VITE_API_URL',
  'VITE_WS_URL',
  'VITE_SOCKET_URL',
  'VITE_DEV_API_TARGET',
  'VITE_DEV_WS_TARGET',
  'VITE_DEV_DISABLE_TURNSTILE',
];

const keys = [
  ...preferredOrder.filter((key) => publicViteEntries.has(key)),
  ...[...publicViteEntries.keys()]
    .filter((key) => !preferredOrder.includes(key))
    .sort((a, b) => a.localeCompare(b)),
];

const output = [
  '# Generated by `pnpm env:local:production`.',
  '# This file is ignored by git. It contains only browser-public VITE_* values.',
  '# API/socket URLs stay blank so local dev uses Vite same-origin proxies to Fly.',
  '# Turnstile is disabled only for local dev; the Vite proxy sends the private bypass header.',
  '',
  ...keys.map((key) => `${key}=${formatEnvValue(publicViteEntries.get(key) ?? '')}`),
  '',
  '# Local dev-only server-side proxy values. Never prefix these with VITE_.',
  `${DEV_TURNSTILE_BYPASS_TOKEN}=${formatEnvValue(devTurnstileBypassToken)}`,
  '',
].join('\n');

writeFileSync(targetPath, output, { mode: 0o600 });

console.log(`Wrote ${path.relative(rootDir, targetPath)}`);
console.log(`Copied ${keys.length} public VITE_* values`);
console.log(`Turnstile: ${publicViteEntries.get('VITE_TURNSTILE_SITE_KEY') ? 'enabled' : 'missing'}`);
console.log(`Dev API proxy target: ${PROD_API_TARGET}`);
console.log(`Dev socket proxy target: ${PROD_WS_TARGET}`);
console.log(`Dev Turnstile proxy bypass token: ${devTurnstileBypassToken ? 'present' : 'missing'}`);
